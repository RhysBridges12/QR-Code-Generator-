    def test_format_string(self):
        for ec_level, mask_pattern, expected_string in self.format_info_tuples:
            generated_string = generate_format_string(ec_level, mask_pattern)

            assert generated_string == expected_string

    def test_format_placement(self):
        # Testing with 000100000111011
        generated_string = generate_format_string(Error_Correction_Level.H, 7)
        test_matrix = place_format_string(self.pre_format_matrix, generated_string)
        npt.assert_array_equal(test_matrix, self.post_format_matrix)

        # Testing with 111100010011101 
        generated_string2 = generate_format_string(Error_Correction_Level.L, 3)
        test_matrix2 = place_format_string(self.pre_format_matrix2, generated_string2)
        npt.assert_array_equal(test_matrix2, self.post_format_matrix2)
        
    def test_padding(self):
        padded_test = pad_matrix(self.post_format_matrix)
        npt.assert_array_equal(padded_test, self.post_padding_matrix)
